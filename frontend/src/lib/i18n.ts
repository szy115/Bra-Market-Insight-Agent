const dictionaries: Record<Locale, Record<string, string>> = { zh, en };

export function loadLocale(): Locale {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    return raw === "en" || raw === "zh" ? raw : "zh";
  } catch {
    return "zh";
  }
}

export function saveLocale(locale: Locale): void {
  localStorage.setItem(STORAGE_KEY, locale);
}

export function makeTranslator(locale: Locale): Translator {
  return (key, fallback) => dictionaries[locale][key] ?? fallback ?? en[key] ?? key;
}

export function formatMessage(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`));
}
